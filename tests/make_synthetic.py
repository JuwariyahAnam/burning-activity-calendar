"""
SYNTHETIC test data in FIRMS CSV format. NOT real fire data.

AI disclosure: generated by code written with Claude (Anthropic).
Use only to check that the code runs. Never show it in the demo or
submission; use real NASA FIRMS downloads there.

The generator has a known answer: MODIS sees a fixed share of the "true"
burning cells that varies by season, and true activity is flat over the
years. A correct harmonization should therefore show no jump in 2012.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

rng = np.random.default_rng(7)
out = Path(sys.argv[1] if len(sys.argv) > 1 else "tests/synthetic_raw")
out.mkdir(parents=True, exist_ok=True)

days = pd.date_range("2003-01-01", "2026-11-13", freq="D")
season = {10: 60, 11: 90, 4: 25, 5: 35}          # mean true burning cells/day
modis_share = {10: 0.30, 11: 0.22, 4: 0.45, 5: 0.40}

modis, viirs = [], []
for d in days:
    lam = season.get(d.month, 1.0) * (1.6 if d.year == 2016 else 1.0)
    n = rng.poisson(lam)
    lat = rng.uniform(29.5, 31.5, n)
    lon = rng.uniform(74.5, 76.5, n)
    seen_m = rng.random(n) < modis_share.get(d.month, 0.35)
    for la, lo in zip(lat[seen_m], lon[seen_m]):
        modis.append((la, lo, d.date(), "0815", "Aqua", rng.integers(35, 100), 0))
    if d >= pd.Timestamp("2012-01-20") and d <= pd.Timestamp("2026-11-02"):
        for la, lo in zip(lat, lon):
            for _ in range(rng.integers(1, 4)):   # several pixels per fire
                viirs.append((la + rng.normal(0, .003), lo + rng.normal(0, .003),
                              d.date(), "0800", "N", rng.choice(["n", "h", "l"],
                                                               p=[.7, .2, .1])))
    if d >= pd.Timestamp("2018-04-01"):
        for la, lo in zip(lat, lon):
            viirs.append((la, lo, d.date(), "0750", "N20", "n"))

m = pd.DataFrame(modis, columns=["latitude", "longitude", "acq_date", "acq_time",
                                 "satellite", "confidence", "type"])
m["instrument"] = "MODIS"; m["frp"] = 20.0; m["brightness"] = 320.0
v = pd.DataFrame(viirs, columns=["latitude", "longitude", "acq_date", "acq_time",
                                 "satellite", "confidence"])
v["instrument"] = "VIIRS"; v["frp"] = 5.0; v["bright_ti4"] = 330.0
m.to_csv(out / "SYNTHETIC_modis.csv", index=False)
v.to_csv(out / "SYNTHETIC_viirs.csv", index=False)
print(len(m), "MODIS rows,", len(v), "VIIRS rows ->", out)
